import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  assertTimeZone,
  buildReportSummary,
  createHistoryLoader,
  generateHtmlReport,
  generateJUnitXml,
  generateMarkdownSummary,
  generateReports,
  mergeReports,
  reportFileBase
} from '../src/report';
import { sampleSummary } from './fixtures/summary';

function tempDir(): string {
  return mkdtempSync(join(tmpdir(), 'neo-reporter-'));
}

function runResults(projectRoot: string): CypressCommandLine.CypressRunResult {
  return {
    browserName: 'chrome',
    browserVersion: '141',
    totalDuration: 5000,
    totalSuites: 1,
    totalTests: 2,
    totalPassed: 1,
    totalFailed: 1,
    totalPending: 0,
    totalSkipped: 0,
    config: { projectRoot, baseUrl: 'https://staging.acme.test', viewportWidth: 1280, viewportHeight: 720 },
    runs: [
      {
        spec: { absolute: join(projectRoot, 'cypress/e2e/cart.cy.js'), name: 'cart.cy.js' },
        stats: { tests: 2, passes: 1, failures: 1, pending: 0, skipped: 0, duration: 5000 },
        screenshots: [],
        video: null,
        tests: [
          { title: ['Cart', 'adds an item'], state: 'passed', duration: 1000, attempts: [{ state: 'passed' }], displayError: null },
          {
            title: ['Cart', 'shows the total'],
            state: 'failed',
            duration: 4000,
            attempts: [{ state: 'failed' }],
            displayError: 'AssertionError: expected 500 to equal 200'
          }
        ]
      }
    ]
  } as unknown as CypressCommandLine.CypressRunResult;
}

test('html report shows the team name and the chosen time zone', () => {
  const html = generateHtmlReport(sampleSummary());
  assert.match(html, /<title>acme-storefront - E2E regression · Web QA team<\/title>/);
  assert.match(html, /Web QA team · Run of Nov 6, 2026, 11:42 AM \(Europe\/Paris\)/);
  assert.match(html, /data-default-theme="auto"/);
  assert.match(html, /Generated by <a href="https:\/\/github.com\/mcello23\/cypress-neo-reporter"/);
});

test('html report follows the time zone option', () => {
  const html = generateHtmlReport({ ...sampleSummary(), timeZone: 'America/New_York' });
  assert.match(html, /Run of Nov 6, 2026, 5:42 AM \(America\/New_York\)/);
});

test('html report leaves the team out when there is none', () => {
  const html = generateHtmlReport({ ...sampleSummary(), teamName: undefined });
  assert.match(html, /<title>acme-storefront - E2E regression<\/title>/);
  assert.doesNotMatch(html, /Web QA team/);
});

test('html report starts in the configured theme', () => {
  assert.match(generateHtmlReport({ ...sampleSummary(), theme: 'light' }), /data-theme="light" data-default-theme="light"/);
  assert.match(generateHtmlReport({ ...sampleSummary(), theme: 'dark' }), /data-theme="dark" data-default-theme="dark"/);
});

test('markdown summary links the report only when a url is given', () => {
  const summary = sampleSummary();
  assert.match(generateMarkdownSummary(summary, 'https://example.com/report.html'), /\(https:\/\/example.com\/report.html\)/);
  assert.doesNotMatch(generateMarkdownSummary(summary), /Open the full HTML report/);
  assert.match(generateMarkdownSummary(summary), /7 failed · 1 flaky · 65 passed/);
});

test('junit xml has one testcase per test and the failures', () => {
  const summary = sampleSummary();
  const xml = generateJUnitXml(summary);
  assert.equal(xml.match(/<testcase /g)?.length, summary.totalTests);
  assert.equal(xml.match(/<failure /g)?.length, summary.totalFailed);
});

test('summary keeps the spec extension and hides the team when showTeamName is false', () => {
  const projectRoot = tempDir();
  const summary = buildReportSummary(runResults(projectRoot), projectRoot, { teamName: 'Web QA team', showTeamName: false });
  assert.equal(summary.teamName, undefined);
  assert.equal(summary.specs[0].specFile, 'cypress/e2e/cart.cy.js');
  assert.equal(summary.timeZone, Intl.DateTimeFormat().resolvedOptions().timeZone);
});

test('project name defaults to the package.json name', () => {
  const projectRoot = tempDir();
  writeFileSync(join(projectRoot, 'package.json'), JSON.stringify({ name: 'my-app' }));
  assert.equal(buildReportSummary(runResults(projectRoot), projectRoot).projectName, 'my-app');
});

test('generateReports writes the four outputs named after the report', async () => {
  const projectRoot = tempDir();
  const files = await generateReports(runResults(projectRoot), {
    projectName: 'acme-storefront',
    reportName: 'E2E regression',
    history: false
  });
  const base = join(projectRoot, 'cypress/reports/E2E-regression');
  assert.deepEqual(files, {
    json: `${base}.json`,
    junit: `${base}.junit.xml`,
    html: `${base}.html`,
    markdown: `${base}.summary.md`
  });
  Object.values(files).forEach(file => assert.ok(existsSync(file), file));
});

test('generateReports writes only the requested outputs', async () => {
  const projectRoot = tempDir();
  const files = await generateReports(runResults(projectRoot), { projectName: 'my-app', outputs: ['junit'], history: false });
  assert.deepEqual(Object.keys(files), ['junit']);
  assert.ok(files.junit?.endsWith('my-app.junit.xml'));
});

test('mergeReports combines shard JSON files and skips merged ones', async () => {
  const root = tempDir();
  const shard = sampleSummary();
  for (const name of ['shard-1', 'shard-2']) {
    mkdirSync(join(root, name));
    writeFileSync(join(root, name, 'E2E-regression.json'), JSON.stringify(shard));
  }
  writeFileSync(join(root, 'old-merge.json'), JSON.stringify({ ...shard, mergedFrom: 2 }));
  const result = await mergeReports({ reportRoot: root, history: false });
  assert.ok(result);
  assert.equal(result.summary.totalTests, shard.totalTests * 2);
  assert.equal(result.summary.mergedFrom, 2);
  assert.deepEqual(Object.keys(result.files), ['html', 'markdown']);
  assert.ok(readFileSync(result.files.html!, 'utf-8').includes('Web QA team'));
});

test('mergeReports returns null when there is nothing to merge', async () => {
  assert.equal(await mergeReports({ reportRoot: tempDir(), history: false }), null);
});

test('unknown time zones fail fast', () => {
  assert.throws(() => assertTimeZone('Mars/Olympus'), /Unknown timeZone "Mars\/Olympus"/);
  assert.doesNotThrow(() => assertTimeZone('Europe/Paris'));
});

test('report file names are safe', () => {
  assert.equal(reportFileBase('E2E regression'), 'E2E-regression');
  assert.equal(reportFileBase('@acme/storefront'), 'acme-storefront');
  assert.equal(reportFileBase('***'), 'report');
});

test('no built-in organization: history is off without a token or a target', t => {
  const env = { ...process.env };
  t.after(() => {
    process.env = env;
  });
  delete process.env.SYSTEM_ACCESSTOKEN;
  delete process.env.AZURE_DEVOPS_PAT;
  delete process.env.SYSTEM_COLLECTIONURI;
  delete process.env.SYSTEM_TEAMFOUNDATIONCOLLECTIONURI;
  delete process.env.SYSTEM_TEAMPROJECT;
  assert.equal(createHistoryLoader({}), null);
  process.env.AZURE_DEVOPS_PAT = 'token';
  t.mock.method(console, 'warn', () => undefined);
  t.mock.method(globalThis, 'fetch', async () => {
    throw new Error('offline');
  });
  assert.equal(createHistoryLoader({}), null);
  assert.equal(createHistoryLoader(false), null);
  assert.notEqual(createHistoryLoader({ organization: 'your-org', project: 'your-project' }), null);
});
